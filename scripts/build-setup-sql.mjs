// Combines every database migration (and optionally the sample data) into ONE
// file you can paste into the Supabase SQL Editor. Use this when
// `npx supabase db push` can't connect (for example on school Wi-Fi).
//
//   npm run db:bundle   → supabase/setup-all.sql            (tables + sample data)
//                         supabase/setup-all-no-sample.sql  (tables only, for the real store)
//
// The file also records each migration as "applied", so a later
// `npx supabase db push` won't try to run them a second time.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

function build(includeSeed) {
  const parts = [
    `-- =============================================================================
-- School Store — complete database setup (generated by \`npm run db:bundle\`)
-- =============================================================================
-- HOW TO USE: Supabase → SQL Editor → New query → paste ALL of this → Run.
-- Run it only ONCE, on a new project. Don't edit this file; edit the files in
-- supabase/migrations/ and regenerate it instead.
-- ${includeSeed ? "Includes SAMPLE DATA (fake products, orders and sales) for testing." : "No sample data: use this for the real store."}
-- =============================================================================

-- Stop if the store tables already exist, so nothing gets created twice.
do $$
begin
  if to_regclass('public.products') is not null then
    raise exception 'The store database is already set up. Nothing was changed.';
  end if;
end $$;
`,
  ];

  for (const f of files) {
    parts.push(`\n-- >>>>>>>>>>>>>>>>>>>>>>>> ${f} >>>>>>>>>>>>>>>>>>>>>>>>\n`);
    parts.push(readFileSync(`${dir}/${f}`, "utf8"));
  }

  if (includeSeed) {
    parts.push(`\n-- >>>>>>>>>>>>>>>>>>>>>>>> seed.sql (sample data) >>>>>>>>>>>>>>>>>>>>>>>>\n`);
    parts.push(readFileSync("supabase/seed.sql", "utf8"));
  }

  // Tell the Supabase CLI these migrations are already applied.
  const versions = files.map((f) => {
    const [version, ...name] = f.replace(/\.sql$/, "").split("_");
    return `('${version}', '${name.join("_")}')`;
  });
  parts.push(`
-- >>>>>>>>>>>>>>>>>>>>>>>> record what was applied >>>>>>>>>>>>>>>>>>>>>>>>
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (
  version    text primary key,
  statements text[],
  name       text
);
insert into supabase_migrations.schema_migrations (version, name) values
  ${versions.join(",\n  ")}
on conflict (version) do nothing;

select 'School Store database is ready!' as result;
`);
  return parts.join("");
}

writeFileSync("supabase/setup-all.sql", build(true));
writeFileSync("supabase/setup-all-no-sample.sql", build(false));
console.log("Wrote supabase/setup-all.sql and supabase/setup-all-no-sample.sql");
